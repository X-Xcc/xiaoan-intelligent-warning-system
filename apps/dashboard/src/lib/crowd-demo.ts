export function crowdDemoAt(value: number) {
  const second = Math.min(60, Math.max(0, Number.isFinite(value) ? Math.round(value) : 0));
  const count = 19 + Math.floor(second * 9 / 60);
  return {
    synthetic: true,
    second,
    count,
    density: Number((count / 10).toFixed(1)),
    netIncrease: count - 19,
    growthPercent: Math.round((count - 19) / 19 * 100),
    dwellSeconds: 146 + second,
    overdueCount: 8 + Math.floor(second / 15),
    elevated: count >= 25,
  };
}

export function crowdTime(seconds: number) {
  return `${String(Math.floor(seconds / 60)).padStart(2, '0')}:${String(seconds % 60).padStart(2, '0')}`;
}

