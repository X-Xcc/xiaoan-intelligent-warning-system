def additional_subjects() -> list[dict[str, Any]]:
    return [
        {
            "subjectId": f"SUBJECT-{code}-{index:03d}",
            "subject": title,
            "category": category,
            "equipment": ["课程资料与训练记录", "教官指定的训练器材已确认"],
            "standard": {
                "label": "按本单位教学计划与考核要求执行",
                "assessmentMode": "instructor",
            },
            "basis": [
                f"科目分类：{category}",
                "本系统整理的训练目录；内容、时长及达标要求由本单位教官确认。",
            ],
        }
        for code, category, titles in SUBJECT_GROUPS
        for index, title in enumerate(titles, 1)
    ]


def training_subjects(samples: list[dict[str, Any]]) -> list[dict[str, Any]]:
    categories = ["警用装备与通信", "巡逻处警与警务战术", "专业警种与专门技能"]
    legacy = [
        {
            "subjectId": item["taskId"], "subject": item["subject"],
            "category": category, "equipment": item["equipment"],
            "standard": item["standard"], "basis": item["basis"],
        }
        for item, category in zip(samples, categories)
    ]
    return deepcopy([*legacy, *additional_subjects()])
